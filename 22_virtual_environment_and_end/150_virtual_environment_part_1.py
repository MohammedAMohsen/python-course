# ما هي البيئة الافتراضية؟
# مجلد مستقل فيه نسخة خاصة من بايثون ومكتباتها لمشروع واحد فقط
# لماذا نحتاجها؟
# لو مشروعان يحتاجان إصدارين مختلفين من نفس المكتبة، كل مشروع يأخذ بيئته الخاصة ولا يتعارضان
# وأيضا تبقى مكتبات النظام نظيفة ولا نخربها بتثبيت كل شيء عليها
# ----------------------------------------
# كل الأوامر التالية تكتب في الطرفية وليس داخل ملف بايثون
# ----------------------------------------

# pip list                       # عرض المكتبات المثبتة حاليا
# mkdir envs && cd envs          # إنشاء مجلد للبيئات والدخول إليه
# python --help                  # عرض أوامر بايثون المتاحة
# python -m venv ai              # إنشاء بيئة افتراضية اسمها ai
# python -m venv pen             # إنشاء بيئة ثانية اسمها pen

# تفعيل البيئة، والأمر يختلف حسب النظام:
# source ai/bin/activate         # لينكس وماك
# source ai/Scripts/activate     # ويندوز داخل Git Bash
# ai\Scripts\activate            # ويندوز داخل CMD أو PowerShell
# بعد التفعيل يظهر اسم البيئة بين قوسين في بداية سطر الطرفية مثل (ai)

# python -m pip install --upgrade pip   # تحديث أداة التثبيت داخل البيئة
# which python                   # يعرض مسار بايثون المستخدم الآن، ويجب أن يكون داخل مجلد البيئة
# deactivate                     # الخروج من البيئة والرجوع لبايثون النظام
# rm -rf ai                      # حذف البيئة نهائيا، لأنها مجرد مجلد
